/**
 * v3 item catalogue: gathering materials for every zone, crafted region sets, loot boxes,
 * the guardian charm, and the "secret" relics (the rarest things in Nexus).
 * Synced into the `items` table on boot (see services/content.js); admin-made items are untouched.
 *
 * I(key, en, ar, desc, type, rarity, value, weight, stats?, use?, slot?)
 */
const I = (key, name, nameAr, description, type, rarity, value, weight, stats = {}, use = null, slot = null) => ({
  key,
  name,
  nameAr,
  description,
  type,
  rarity,
  value,
  weight,
  stats,
  use,
  slot,
  usable: Boolean(use),
  equippable: Boolean(slot),
});

const mat = (key, name, nameAr, description, rarity, value, weight = 0.5) => I(key, name, nameAr, description, 'material', rarity, value, weight);

