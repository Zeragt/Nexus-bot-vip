import { WORLD_BOSSES } from './bosses.js';

const mat = (key, name, nameAr, rarity, value, description, weight = 0.3) => ({
  key,
  name,
  nameAr,
  description,
  type: 'material',
  rarity,
  value,
  weight,
});

const gear = (key, name, nameAr, slot, rarity, value, stats, description, weight = 3) => ({
  key,
  name,
  nameAr,
  description,
  type: slot === 'weapon' ? 'weapon' : slot === 'armor' ? 'armor' : 'accessory',
  rarity,
  value,
  weight,
  stats,
  equippable: true,
  slot,
});

const potion = (key, name, nameAr, rarity, value, useEffect, description) => ({
  key,
  name,
  nameAr,
  description,
  type: 'consumable',
  rarity,
  value,
  weight: 0.3,
  useEffect,
  usable: true,
});

